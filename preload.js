// The only bridge between the windows and the main process.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  platform: process.platform,
  // Read once as the page loads, so the art draws in the right style straight away.
  artStyle: ipcRenderer.sendSync('style:get'),
  setArtStyle: (s) => ipcRenderer.invoke('style:set', s),
  getState: () => ipcRenderer.invoke('state:get'),
  addHabit: (h) => ipcRenderer.invoke('habit:add', h),
  updateHabit: (id, h) => ipcRenderer.invoke('habit:update', id, h),
  deleteHabit: (id) => ipcRenderer.invoke('habit:delete', id),
  toggleHabit: (id) => ipcRenderer.invoke('habit:toggle', id),
  onState: (cb) => ipcRenderer.on('state:changed', (_e, s) => cb(s)),
  movePet: (x, y) => ipcRenderer.send('pet:move', x, y),
  dropPet: () => ipcRenderer.send('pet:drop'),
  togglePanel: () => ipcRenderer.send('panel:toggle'),
  closePanel: () => ipcRenderer.send('panel:close'),
  petMenu: () => ipcRenderer.send('pet:menu'),
  onBubble: (cb) => ipcRenderer.on('bubble:show', (_e, msg) => cb(msg)),
  bubbleSize: (h) => ipcRenderer.send('bubble:size', h),
  onTalking: (cb) => ipcRenderer.on('pet:talking', (_e, on) => cb(on)),
  onFed: (cb) => ipcRenderer.on('pet:fed', (_e, info) => cb(info)),
  onStageUp: (cb) => ipcRenderer.on('pet:stageup', (_e, stage) => cb(stage)),
  poke: () => ipcRenderer.send('pet:poke'),
  hover: (on) => ipcRenderer.send('pet:hover', on),
  onAct: (cb) => ipcRenderer.on('pet:act', (_e, a) => cb(a)),
  onVisitorAct: (cb) => ipcRenderer.on('visitor:act', (_e, a) => cb(a)),
  setUserName: (n) => ipcRenderer.invoke('user:rename', n),
  onEditUser: (cb) => ipcRenderer.on('user:edit', () => cb()),
  renamePet: (n) => ipcRenderer.invoke('pet:rename', n),
  recolorPet: (c) => ipcRenderer.invoke('pet:recolor', c),
  setSpecies: (sp) => ipcRenderer.invoke('pet:species', sp),
  openCeremony: (asPreview) => ipcRenderer.send('ceremony:open', asPreview),
  ceremonyInfo: () => ipcRenderer.invoke('ceremony:info'),
  ceremonyConfirm: (name) => ipcRenderer.invoke('ceremony:confirm', name),
  ceremonyClose: () => ipcRenderer.send('ceremony:close'),
  openGarden: (sample) => ipcRenderer.send('garden:open', sample),
  gardenInfo: () => ipcRenderer.invoke('garden:info'),
  setHangout: (id) => ipcRenderer.invoke('hangout:set', id),
  onGarden: (cb) => ipcRenderer.on('garden:changed', (_e, d) => cb(d)),
  setVisitor: (id, on) => ipcRenderer.invoke('visitor:set', id, on),
  visitorInfo: (id) => ipcRenderer.invoke('visitor:info', id),
  visitorHi: (id) => ipcRenderer.send('visitor:hi', id),
  openHistory: () => ipcRenderer.send('history:open'),
  historyInfo: () => ipcRenderer.invoke('history:info'),
  historyMonth: (y, m) => ipcRenderer.invoke('history:month', y, m),
  onHistory: (cb) => ipcRenderer.on('history:changed', () => cb()),
});
